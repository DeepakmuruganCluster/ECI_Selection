"""Import the Siemens miniature circuit breaker ordering tables of Catalog LV 10 · 2026 (chapter 3, basic units).

    .venv/bin/python scripts/import_lv10_mcb.py

Source: SIE-LV10-2026. Each series is a two-page spread (even PDF page = left half, odd = right half); the text layer of
both pages holds the whole spread, so every article is cited on the page where it is actually printed (character
position inside that page's box). Values are copied as printed: series heading kA (rated switching capacity of the
series), poles, rated voltage, mounting width, characteristic, rated current and article number.
"""
from __future__ import annotations

import re
from pathlib import Path

import pypdfium2 as pdfium
import yaml

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "sources" / "pdf" / "manufacturer" / "siemens" / "LV10_2026_EN_202601160649587174.pdf"
OUT = ROOT / "data" / "makers" / "siemens" / "lv10_mcb.yaml"
SPREADS = {280: "5SL3", 282: "5SL6", 284: "5SL4", 294: "5SY6", 296: "5SY4", 298: "5SP4", 304: "5SY7", 306: "5SY8"}
HYPHENS = "\u2010\u2011\u2012\u00ad"     # printed hyphens inside article numbers; the en dash marks an empty cell


def norm(s: str) -> str:
    for h in HYPHENS:
        s = s.replace(h, "-")
    return s.replace("\r", "").replace("\xa0", " ")


def printed_on(pdf, pno: int, article: str) -> int:
    """The PDF page (pno or pno+1) on which the article is visibly printed."""
    for p in (pno, pno + 1):
        page = pdf[p - 1]
        w, h = page.get_size()
        tp = page.get_textpage()
        s = tp.search(article, match_case=True, match_whole_word=False)
        hit = s.get_next()
        while hit:
            idx, n = hit
            x0, y0, x1, y1 = tp.get_charbox(idx)
            if 0 <= x0 <= w and 0 <= y0 <= h:
                return p
            hit = s.get_next()
    raise ValueError(f"{article} not visible on p.{pno}/{pno + 1}")


def spread(pdf, pno: int, series: str):
    text = norm(pdf[pno - 1].get_textpage().get_text_range())
    lines = [ln.strip() for ln in text.split("\n")]
    title = next(i for i, ln in enumerate(lines) if ln == f"{series} miniature circuit breakers")
    ka = next(ln for ln in lines[title + 1:title + 3] if ln.endswith("kA"))
    poles = next(ln.split() for ln in lines if re.fullmatch(r"1P( [0-9P+N]+)+", ln))
    un_line = next(ln for ln in lines if re.search(r"\d+ V AC", ln) and "Rated" not in ln or ln.startswith("Rated voltage Un"))
    un = re.findall(r"(\d+(?:/\d+)? V AC)", un_line)
    mw = re.findall(r"(\d+(?:\.\d+)? MW)", next(ln for ln in lines if re.search(r"\d MW", ln)))
    chars_i = next(i for i, ln in enumerate(lines) if re.fullmatch(r"([A-D] )+[A-D]", ln))
    chars = lines[chars_i].split()
    per = len(chars) // len(poles)
    assert per * len(poles) == len(chars) and len(un) == len(poles) == len(mw), (series, poles, un, mw, chars)
    out, skipped = [], []
    for ln in lines[chars_i + 1:]:
        m = re.match(r"^(\d+(?:\.\d+)?) A (.+)$", ln)
        if not m:
            if ln.startswith("■"):
                skipped.append(ln)
            if ln.startswith("Mounting concept") or ln.startswith("Accessories"):
                break
            continue
        cells = m.group(2).replace("–", "–").split()
        if len(cells) == len(chars) + 1:          # 5SY7: leading "main MCB, line side of meter" column
            if cells[0] != "–":
                skipped.append(ln)
            cells = cells[1:]
        if len(cells) != len(chars):
            raise ValueError(f"{series} p.{pno}: {len(cells)} cells, {len(chars)} expected: {ln!r}")
        for k, a in enumerate(cells):
            if a == "–":
                continue
            assert a.startswith(series), (series, a)
            pi = k // per
            out.append({"article": a, "series": series, "breaking_capacity": ka, "poles": poles[pi], "un": un[pi],
                        "width": mw[pi], "curve": chars[k], "in_a": float(m.group(1)) if "." in m.group(1) else int(m.group(1)),
                        "page": printed_on(pdf, pno, a)})
    return out, skipped


if __name__ == "__main__":
    pdf = pdfium.PdfDocument(str(PDF))
    rows, skipped = [], []
    for pno, series in SPREADS.items():
        r, s = spread(pdf, pno, series)
        rows += r
        skipped += [f"p.{pno} {x}" for x in s]
    arts = [r["article"] for r in rows]
    assert len(arts) == len(set(arts)), "duplicate article"
    data = {"source": {"ref": "SIE-LV10-2026",
                       "section": "Chapter 3 Miniature Circuit Breakers, basic units: 5SL3, 5SL6, 5SL4, 5SY6, 5SY4, 5SP4, 5SY7, 5SY8 ordering tables",
                       "note": "'breaking_capacity' = the kA printed under each series title; 'page' = PDF page where the article is printed"},
            "rows": rows, "skipped": skipped}
    OUT.write_text("# Generated by scripts/import_lv10_mcb.py — do not edit by hand.\n" +
                   yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200))
    from collections import Counter
    print(len(rows), "articles;", dict(Counter((r["series"], r["breaking_capacity"]) for r in rows)), "; skipped", len(skipped))
