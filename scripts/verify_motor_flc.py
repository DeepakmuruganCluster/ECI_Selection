"""G6 verification for motor_flc — writes components/motor_flc/VERIFY.md.

1. Independent re-extraction: reads pages 28–29 of the SIRIUS manual with
   pdfplumber (not the hand transcription) and compares every guide value.
2. Real project: runs every WNS2503 feeder through v2 and compares with the
   client's list value and with v1's design FLC.

Needs pdfplumber. Usage:
    python scripts/verify_motor_flc.py [path/to/WNS2503_layer0.json]
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pdfplumber  # noqa: E402

from components.motor_flc.select import _guide, select  # noqa: E402
from core.provenance import SOURCES  # noqa: E402

V1_JSON = Path("/Users/deepak/Documents/panel-selector/projects/WNS2503/out/WNS2503_layer0.json")
ROW = re.compile(r"^(\d+(?:\.\d+)?)(?:\s*\d\))?\s+(\d+(?:\.\d+)?)\s+\d")   # "kW [3)] A min…"


def pdf_table() -> dict[float, tuple[float, int]]:
    g = _guide()
    found: dict[float, tuple[float, int]] = {}
    with pdfplumber.open(SOURCES / g["reference"]["file"]) as pdf:
        for page in (28, 29):
            for line in (pdf.pages[page - 1].extract_text() or "").splitlines():
                m = ROW.match(line.strip())
                if m:
                    kw, a = float(m.group(1)), float(m.group(2))
                    if kw in found and found[kw][0] != a:
                        raise SystemExit(f"PDF gives two currents for {kw} kW")
                    found.setdefault(kw, (a, page))
    return found


def main():
    out = [f"# Motor FLC — G6 verification ({date.today().isoformat()})", "",
           "Generated by `scripts/verify_motor_flc.py`.", ""]

    # 1 ---------------------------------------------------------------------------
    pdf = pdf_table()
    rows = _guide()["rows"]
    mism = [(r["kw"], r["flc_a"], pdf.get(float(r["kw"]))) for r in rows
            if pdf.get(float(r["kw"]), (None,))[0] != float(r["flc_a"]) or pdf[float(r["kw"])][1] != r["page"]]
    extra = sorted(set(pdf) - {float(r["kw"]) for r in rows})
    out += ["## 1. Data file vs automatic re-extraction of the PDF (pp. 28–29)", "",
            f"- rows in data file: {len(rows)}; kW values found in the PDF: {len(pdf)}",
            f"- mismatches (value or page): **{len(mism)}**" + "".join(f"\n  - {k} kW: file {a} A, PDF {p}" for k, a, p in mism),
            f"- in the PDF but not in the file: {extra or 'none'}", ""]

    # 2 ---------------------------------------------------------------------------
    if len(sys.argv) > 1:
        src = Path(sys.argv[1])
    else:
        src = V1_JSON
    if src.exists():
        feeders = json.loads(src.read_text())["feeders"]
        lines, stats = [], Counter()
        for f in feeders:
            if f.get("load_type") == "spare" or not f.get("kw"):
                stats["skipped (spare / no kW)"] += 1
                continue
            r = select(kw=f["kw"], load_type="heater" if f.get("load_type") == "heater" else "motor",
                       phases=f.get("phases") or 3, voltage_v=f.get("voltage") or 400,
                       frequency_hz=f.get("frequency") or 50, client_flc_a=f.get("flc_client"))
            stats[r.status] += 1
            v2 = r.value.get("flc_a")
            v1 = f.get("flc")
            same_v1 = v2 is not None and v1 is not None and abs(v2 - v1) < 0.005
            stats["v2 = v1" if same_v1 else "v2 ≠ v1"] += 1
            note = "; ".join(f"{c.rule}: {c.value}" for c in r.checks if c.verdict in ("warn", "fail"))
            lines.append(f"| {f['id']} | {', '.join(f.get('tags', [])[:2])} | {f['kw']:g} | {f.get('phases')}ph "
                         f"{f.get('voltage'):g} V | {f.get('flc_client') if f.get('flc_client') is not None else '—'} "
                         f"| {v1 if v1 is not None else '—'} | {v2 if v2 is not None else '—'} | {r.basis} | {r.status} "
                         f"| {note.replace('|', '/')} |")
        out += [f"## 2. WNS2503 ({len(feeders)} feeders from `{src.name}`)", "",
                "Client value = client's load list (checked, never used). v1 = old engine's design FLC.", "",
                "| " + " · ".join(f"{k}: {v}" for k, v in sorted(stats.items())) + " |", "|---|", "",
                "| Feeder | Tags | kW | Supply | Client A | v1 A | v2 A | v2 basis | v2 status | Warnings / refusals |",
                "|---|---|---|---|---|---|---|---|---|---|", *lines, ""]
    else:
        out += ["## 2. WNS2503", "", f"skipped: {src} not found", ""]

    (ROOT / "components" / "motor_flc" / "VERIFY.md").write_text("\n".join(out))
    print("\n".join(out[:14]))


if __name__ == "__main__":
    main()
