"""G6 for the panel assembly — writes components/panel/VERIFY.md.

Runs the WNS2503 load list (v1 Layer 0 output: tags, kW, starter, qty/standby, cable length)
through the v2 chain for each panel, in two cooling cases, and reports what is selected,
what is open and why, the BOM and the heat. Client FLC values are NOT passed (they are
formula values, not nameplates).
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from components.panel.select import select  # noqa: E402

V1_JSON = Path("/Users/deepak/Documents/panel-selector/projects/WNS2503/out/WNS2503_layer0.json")
STARTER = {"DOL": "DOL", "VFD": "VFD", "SS": "SS"}


def load_lists() -> dict[str, str]:
    feeders = json.loads(V1_JSON.read_text())["feeders"]
    out: dict[str, list[str]] = {}
    for f in feeders:
        if f.get("load_type") == "spare" or not f.get("kw"):
            continue
        starter = "HEATER" if f.get("load_type") == "heater" else STARTER.get(f["starter"], f["starter"])
        tag = f["id"]
        opts = [f"cable={f.get('cable_length_m') or 50:g}", f"qty={f.get('qty') or 1}", f"ph={f.get('phases') or 3}",
                f"standby={f.get('standby') or 0}"]
        out.setdefault(f["panel"], []).append(f"{tag} {f['kw']:g} {starter} {' '.join(opts)}")
    return {p: "\n".join(lines) for p, lines in out.items()}


def main():
    out = [f"# Panel assembly — G6 verification ({date.today().isoformat()})", "",
           "Generated by `scripts/verify_panel.py`. WNS2503 load lists from the v1 Layer 0 output; motor currents "
           "from component 1 (client FLC values not used); fault level 50 kA; motor pf 0.85 (assumed for this run "
           "only); Polycab cable in air at 40 °C; site altitude 1000 m (assumed); ECI line reactor rule ≤ 15 kW; drives protected by fuses.", ""]
    for panel, text in load_lists().items():
        for label, internal, site in (("air-conditioned panel, 35 °C inside, 50 °C site", 35, 50),
                                      ("fan-cooled panel, 55 °C inside, 50 °C site", 55, 50)):
            r = select(load_list=text, fault_ka=50, panel_internal_c=internal, motor_pf=0.85, cable_ambient_c=40,
                       site_ambient_c=site, line_reactor_up_to_kw=15, altitude_m=1000)
            v = r.value
            kinds = Counter((p["component"], p["rule"]) for p in v["open_points"])
            out += [f"## {panel} — {label}", "",
                    f"- lines {v['n_lines']} (units {v['n_units']}): selected **{v['n_selected']}**, "
                    f"open points **{v['n_open']}**",
                    f"- heat from sourced losses: {v['heat_known_w']:g} W (DOL starters not included — no sourced "
                    f"loss); cooling: {v['cooling_method'] or 'not assessed'}"
                    + (f", fan airflow {v['fan_airflow_m3h']:g} m³/h" if v.get("fan_airflow_m3h") else "")
                    + (f", cooling unit {v['cooling_unit_w']:g} W" if v.get("cooling_unit_w") else ""),
                    "- open points by component and rule: "
                    + "; ".join(f"{c} {rule} × {n}" for (c, rule), n in kinds.most_common()), "",
                    "| Article | Description | Qty | Used by |", "|---|---|---|---|",
                    *[f"| {b['article']} | {b['description']} | {b['qty']:g} | {', '.join(b['used_by'][:6])}"
                      f"{' …' if len(b['used_by']) > 6 else ''} |" for b in v["bom"]], ""]
    (ROOT / "components" / "panel" / "VERIFY.md").write_text("\n".join(out))
    print("\n".join(l for l in out if l.startswith(("##", "- "))))


if __name__ == "__main__":
    main()
