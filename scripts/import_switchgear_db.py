"""Import the own switchgear database (OWN-SWG-*) into traceable data files: one row per CSV line, with its line number.

    .venv/bin/python scripts/import_switchgear_db.py

Values are copied as written; nothing is corrected here. Blank and unreadable lines are skipped and listed.
The check that the data files equal the CSV files is tests/test_aux_switchgear.py (G6).
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "sources" / "pdf" / "own" / "switchgears"


def _num(v):
    v = (v or "").strip()
    if not v:
        return None
    try:
        f = float(v.replace("%", ""))
        return int(f) if f == int(f) else f
    except ValueError:
        return v


def _rows(name: str):
    with open(SRC / name, encoding="utf-8-sig", newline="") as f:
        for line, r in enumerate(csv.DictReader(f), 2):
            yield line, {k.strip(): (v or "").strip() for k, v in r.items() if k}


def convert() -> dict[str, dict]:
    out, skipped = {}, []

    def table(ref, name, fn):
        rows = []
        for line, r in _rows(name):
            row = fn(r)
            if row is None:
                skipped.append(f"{name} line {line}")
                continue
            rows.append({**row, "row": line})
        return {"source": {"ref": ref, "note": f"{name}: one row per CSV line ('row' = line number, header = 1)"},
                "rows": rows}

    out["switchgear/own_mcb.yaml"] = table("OWN-SWG-MCB", "MCB.csv", lambda r: r["Part number"] and {
        "make": r["Make"], "poles": _num(r["Pole"]), "in_a": _num(r["Rated Current, In"]), "curve": r["Characteristics"],
        "article": r["Part number"], "trip_lo_a": _num(r["Low Inrush"]), "trip_hi_a": _num(r["High Inrush"])} or None)
    out["switchgear/own_rccb.yaml"] = table("OWN-SWG-RCCB", "RCCB.csv", lambda r: r["Part number"] and {
        "make": r["Make"], "poles": _num(r["Pole"]), "in_a": _num(r["Rated Current, In"]),
        "idn_ma": _num(r["Leakage Current, mA"]), "article": r["Part number"]} or None)
    out["switchgear/own_isolator.yaml"] = table("OWN-SWG-ISO", "isolator.csv", lambda r: r["Part number"] and {
        "make": r["Make"], "poles": _num(r["Pole"]), "in_a": _num(r["Rated Current, In"]), "article": r["Part number"]} or None)
    out["switchgear/own_sa.yaml"] = table("OWN-SWG-SA", "sa.csv", lambda r: r["Part number"] and {
        "make": r["Make"], "poles": _num(r["Pole"]), "config": r["SA configuration"], "article": r["Part number"]} or None)
    out["switchgear/own_pmr.yaml"] = table("OWN-SWG-PMR", "pmr.csv", lambda r: r["Part number"] and {
        "make": r["Make"], "poles": _num(r["Pole"]), "article": r["Part number"]} or None)
    # SMPS rows now come from the AutoBOM database (scripts/import_autobom.py); OWN-SWG-SMPS stays registered.
    return out, skipped


if __name__ == "__main__":
    data, skipped = convert()
    for rel, d in data.items():
        p = ROOT / "data" / "company" / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        head = ("# Generated by scripts/import_switchgear_db.py from the own switchgear database — do not edit by hand.\n"
                "# Authority OWN: no manufacturer document behind these rows; confirm article numbers before ordering.\n")
        p.write_text(head + yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=200))
        print(f"{rel}: {len(d['rows'])} rows")
    print(f"skipped {len(skipped)} blank line(s)", file=sys.stderr)
