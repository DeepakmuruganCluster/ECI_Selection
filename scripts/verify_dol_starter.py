"""G6 verification for dol_starter — writes components/dol_starter/VERIFY.md.

1. Independent re-extraction of the Type 2 table (pp. 28–29) and Table 2-1 (p. 22)
   with pdfplumber, compared field by field with the hand transcription.
2. WNS2503: every DOL feeder through v2 motor_flc → dol_starter, compared with the
   client's MPCB range and with v1's proposed range.

Usage:  python scripts/verify_dol_starter.py
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pdfplumber  # noqa: E402

from components.dol_starter.select import _links, _table, select as dol  # noqa: E402
from components.motor_flc.select import select as flc  # noqa: E402
from core.provenance import SOURCES  # noqa: E402

V1_JSON = Path("/Users/deepak/Documents/panel-selector/projects/WNS2503/out/WNS2503_layer0.json")
NUM = r"(\d+(?:\.\d+)?)"
SEP = r"\s*(?:\.\.\.|…|\.\.)\s*"
ROW = re.compile(rf"^{NUM}\s+{NUM}\s+{NUM}{SEP}{NUM}\s+{NUM}{SEP}{NUM}\s+(3RV2\S+)\s+(3RT2\S+)\s+(S\d+/S\d+)")


def _rng(cell: str):
    a, b = re.findall(NUM, cell.split("\n")[0])[:2]
    return [float(a), float(b)]


def pdf_rows():
    """Cell-level extraction (pdfplumber tables): notes stay inside their own cell."""
    rows = []
    with pdfplumber.open(SOURCES / _table()["reference"]["file"]) as pdf:
        for page in (28, 29):
            for t in pdf.pages[page - 1].extract_tables():
                for raw in t:
                    c = [x for x in raw if x not in (None, "")]
                    if len(c) != 7 or not c[4].startswith("3RV2"):
                        continue
                    r = {"kw": float(c[0]), "range": _rng(c[2]), "range_ie3": _rng(c[3]), "mpcb": c[4],
                         "contactor": c[5], "size": c[6], "page": page}
                    n = re.search(r"up to (\d+) A", c[3].replace("\n", " "))
                    if n:
                        r["ie3_start_max_a"] = float(n.group(1))
                    rows.append(r)
        links = []
        for t in pdf.pages[21].extract_tables():
            for raw in t:
                if raw[-1] and raw[1] and "contactor in size" in raw[1]:
                    m = re.search(r"size (S\d+)(?: (AC|DC))?", raw[1])
                    links.append((m.group(1), m.group(2) or "any", raw[-1].replace("\n", "")))
    return rows, links


def main():
    out = [f"# DOL starter — G6 verification ({date.today().isoformat()})", "",
           "Generated by `scripts/verify_dol_starter.py`.", ""]
    rows, links = pdf_rows()
    mine = _table()["rows"]
    keys = ("kw", "range", "range_ie3", "mpcb", "contactor", "size", "page", "ie3_start_max_a")
    diffs = []
    for i, (a, b) in enumerate(zip(mine, rows)):
        for k in keys:
            va, vb = a.get(k), b.get(k)
            if isinstance(va, list):
                va = [float(x) for x in va]
            if va != vb and not (va is None and vb is None):
                diffs.append(f"row {i + 1} {a['mpcb']} {k}: file {va} / PDF {vb}")
    out += ["## 1. Type 2 table: data file vs automatic re-extraction (pp. 28–29)", "",
            f"- rows in data file: {len(mine)}; 3RV2 rows parsed from the PDF: {len(rows)}",
            f"- field mismatches: **{len(diffs)}**" + "".join(f"\n  - {d}" for d in diffs),
            f"- starting-current notes found: "
            + ", ".join(f"{r['mpcb']} ≤ {r['ie3_start_max_a']:g} A" for r in rows if r.get("ie3_start_max_a")), ""]

    lk = [(r["size"], r["coil"], r["article"]) for r in _links()["rows"]]
    lk_missing = sorted(set(lk) ^ set(links))
    out += ["## 2. Link modules vs p. 22", "",
            f"- link modules in data file: {len(lk)}; contactor link modules in Table 2-1: {len(links)}; "
            f"differences: **{len(lk_missing)}**"
            + "".join(f"\n  - {x}" for x in lk_missing),
            ""]

    if V1_JSON.exists():
        feeders = [f for f in json.loads(V1_JSON.read_text())["feeders"] if f.get("starter") == "DOL"]
        stats, lines = Counter(), []
        for f in feeders:
            r1 = flc(kw=f["kw"], load_type="heater" if f.get("load_type") == "heater" else "motor",
                     phases=f.get("phases") or 3, voltage_v=f.get("voltage") or 400)
            client = f.get("range_client")
            v1 = f.get("range_proposed")
            if r1.status in ("cannot_select", "invalid"):
                stats["FLC not available"] += 1
                lines.append(f"| {f['id']} | {', '.join(f.get('tags', [])[:2])} | {f['kw']:g} | — | "
                             f"{client} | {v1} | — | FLC: {r1.checks[-1].rule} | |")
                continue
            i = r1.value["flc_a"]
            r2 = dol(flc_a=i, flc_basis=r1.basis, ie_class="IE3", fault_ka=50,
                     load_type="heater" if f.get("load_type") == "heater" else "motor")
            stats[f"DOL {r2.status}"] += 1
            rng = r2.value.get("setting_range_a", "—")
            full = next((list(map(float, r["range"])) for r in _table()["rows"] if r["mpcb"] == r2.value.get("mpcb")), None)
            same_client = bool(client and full == client)
            stats["same MPCB as client" if same_client else "different MPCB from client"] += 1
            note = "; ".join(f"{c.rule}" for c in r2.checks if c.verdict in ("warn", "fail"))
            lines.append(f"| {f['id']} | {', '.join(f.get('tags', [])[:2])} | {f['kw']:g} | {i:g} | {client} | {v1} "
                         f"| {r2.value.get('mpcb', '—')} ({full[0]:g}–{full[1]:g}; set {i:g}) | {r2.status} | {note} |" if full else
                         f"| — | {r2.status} | {note} |")
        out += [f"## 3. WNS2503 DOL feeders ({len(feeders)})", "",
                "Run with IE3, fault level 50 kA, **230 V AC coil** (ECI's 24 V DC coil is not yet sourced, R-DOL-07).", "",
                "| " + " · ".join(f"{k}: {v}" for k, v in sorted(stats.items())) + " |", "|---|", "",
                "| Feeder | Tags | kW | v2 FLC A | Client range | v1 range | v2 MPCB (IE1/IE2 range; setting) | v2 status | Warnings |",
                "|---|---|---|---|---|---|---|---|---|", *lines, ""]
    (ROOT / "components" / "dol_starter" / "VERIFY.md").write_text("\n".join(out))
    print("\n".join(out[:20]))


if __name__ == "__main__":
    main()
