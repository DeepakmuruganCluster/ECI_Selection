"""Import the SIRIUS 3RT2 power contactor ordering tables of Catalog IC 10 · 2026 (pages 3/43 to 3/60).

    .venv/bin/python scripts/import_ic10_contactors.py

Source: SIE-IC10-2026, PDF pages 171-188 ("Power contactors for switching motors", AC, DC and AC/DC operation,
coupling contactors for direct PLC control). One row per article: rated data, auxiliary contacts, rated control
supply voltage and version exactly as printed; the spring-loaded twin of each screw article is kept as `article_spring`.
Rows that continue a block (only Uc + article printed) inherit the rated data printed above them, as the table does.
"""
from __future__ import annotations

import re
from pathlib import Path

import pypdfium2 as pdfium
import yaml

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "sources" / "pdf" / "manufacturer" / "siemens" / "SIRIUS_IC10_complete_English_2026_202601291128292156.pdf"
PAGES = range(171, 189)
OUT = ROOT / "data" / "makers" / "siemens" / "ic10_3rt2_contactors.yaml"

ART = r"3RT20\d\d-\d[A-Z]{2}\d\d(?:-\d[A-Z]{2}\d)?"
ROW = re.compile(rf"^(?P<pre>.*?)(?P<screw>{ART})\s+(?P<spring>{ART}|--)\s*$")
UC = re.compile(r"(?P<uc>\d+(?: \.\.\. \d+)?)\s*$")


def operation(text: str) -> str:
    if "DC operation for direct control by PLC" in text:
        return "DC (coupling contactor for PLC)"
    if "AC/DC operation" in text:
        return "AC/DC"
    if "DC operation" in text:
        return "DC"
    return "AC"


def rows():
    pdf = pdfium.PdfDocument(str(PDF))
    out = []
    for pno in PAGES:
        text = pdf[pno - 1].get_textpage().get_text_range().replace("\r", "")
        printed = re.search(r"(\d+/\d+)", text.split("\n")[0] + " " + text.split("\n")[-2])
        op = operation(text)
        size, freq, version, last = None, "", "", {}
        lines = [ln.strip() for ln in text.split("\n")]
        for i, ln in enumerate(lines):
            if m := re.match(r"^Size (S\d+)", ln):
                size, version, freq = m.group(1), "", ""
                continue
            if ln in ("50 Hz AC", "50/60 Hz AC"):
                freq, version = ln, ""
                continue
            if ln.startswith("With "):
                version = ln
                j = i + 1
                while j < len(lines) and not ROW.match(lines[j]) and not lines[j].startswith(("With ", "Size ", "For ", "Operating", "closing", "©", "50")):
                    version += " " + lines[j]
                    j += 1
                continue
            m = ROW.match(ln)
            if not m or size is None:
                continue
            pre = m.group("pre").strip()
            u = UC.search(pre)
            if not u:
                raise ValueError(f"p.{pno}: no Uc in {ln!r}")
            head = pre[:u.start()].split()
            if len(head) == 6:
                last = dict(zip(("ie_ac3_a", "kw_400v", "ie_ac1_a", "aux_ident", "aux_no", "aux_nc"), head))
            elif len(head) == 3:
                last = {**last, **dict(zip(("aux_ident", "aux_no", "aux_nc"), head))}
            elif head:
                raise ValueError(f"p.{pno}: unexpected columns {head} in {ln!r}")
            notes = []

            def num(v):
                if v == "--":
                    return 0
                if m_ := re.fullmatch(r"(\d+(?:\.\d+)?)(\d)\)", v):   # footnote mark fused to the value: '5.51)'
                    notes.append(f"{m_.group(1)} footnote {m_.group(2)})")
                    v = m_.group(1)
                return int(v) if v.isdigit() else float(v)
            out.append({
                "article": m.group("screw"), "article_spring": None if m.group("spring") == "--" else m.group("spring"),
                "type": m.group("screw")[:7], "size": size, "operation": op, "frequency": freq or None,
                "version": version.rstrip() or "standard", "uc_v": u.group("uc"),
                "ie_ac3_a": num(last["ie_ac3_a"]), "kw_400v": num(last["kw_400v"]), "ie_ac1_a": num(last["ie_ac1_a"]),
                "aux_ident": last["aux_ident"], "aux_no": num(last["aux_no"]), "aux_nc": num(last["aux_nc"]),
                "footnotes": notes or None, "page": pno, "printed": printed.group(1) if printed else None,
            })
    return out


if __name__ == "__main__":
    r = rows()
    arts = [x["article"] for x in r]
    dup = {a for a in arts if arts.count(a) > 1}
    data = {"source": {"ref": "SIE-IC10-2026",
                       "section": "Power contactors for switching motors, SIRIUS 3RT contactors 3-pole up to 250 kW: ordering data, AC / DC / AC-DC operation",
                       "note": "'page' = PDF page, 'printed' = catalogue page; screw-terminal article with its spring-loaded twin"},
            "rows": r}
    OUT.write_text("# Generated by scripts/import_ic10_contactors.py — do not edit by hand.\n" +
                   yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200))
    from collections import Counter
    print(len(r), "articles;", Counter((x["size"], x["operation"]) for x in r), "duplicates:", sorted(dup))
