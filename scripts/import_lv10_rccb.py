"""Import the Siemens 5SV RCCB ordering tables of Catalog LV 10 · 2026 (chapter 4, basic units, PDF pages 378-395).

    .venv/bin/python scripts/import_lv10_rccb.py

Source: SIE-LV10-2026. One row per article with the printed type (A, AC, F, B, B+), poles (1P+N / 3P+N), rated
residual current IΔn and rated current In; rows that continue a block inherit IΔn / In as the table prints them.
The tables have several version columns (instantaneous, short-time delayed [G], super resistant [K], selective [S],
N left / right, bulk packaging …). The plain article (no suffix) is the standard instantaneous version; an article
with a suffix is recorded as a variant, to be read on its cited page before use.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pypdfium2 as pdfium
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from import_lv10_mcb import PDF, norm, printed_on  # noqa: E402

OUT = ROOT / "data" / "makers" / "siemens" / "lv10_rccb.yaml"
SPREADS = (378, 380, 382, 384, 386, 388, 390, 392, 394)
ART = re.compile(r"5SV\d{4}-[0-9A-Z]+")


def spread(pdf, pno: int):
    lines = [ln.strip() for ln in norm(pdf[pno - 1].get_textpage().get_text_range()).split("\n")]
    head = next(ln for ln in lines if re.match(r"^Type [A-Z+ and]+, [13]P\+N", ln))
    poles = re.search(r"([13]P\+N)", head).group(1)
    high = "high-current" in head
    typ, idn, in_a, out = None, None, None, []
    for ln in lines:
        if re.fullmatch(r"Type (A|AC|F|B|B\+)", ln):
            typ = ln[5:]
            continue
        arts = ART.findall(ln)
        if not arts or typ is None:
            continue
        m = re.match(r"^(?:(\d+) mA )?(?:(\d+) A )?", ln)
        if m.group(1):
            idn = int(m.group(1))
        if m.group(2):
            in_a = int(m.group(2))
        if idn is None or in_a is None:
            raise ValueError(f"p.{pno}: row without IΔn / In: {ln!r}")
        for a in arts:
            out.append({"article": a, "type": typ, "poles": poles, "idn_ma": idn, "in_a": in_a,
                        "version": "standard instantaneous" if re.fullmatch(r"5SV\d{4}-\d", a) else "variant (see page)",
                        "high_current": high, "page": printed_on(pdf, pno, a)})
    return out


if __name__ == "__main__":
    pdf = pdfium.PdfDocument(str(PDF))
    rows = [r for p in SPREADS for r in spread(pdf, p)]
    seen, dup = set(), []
    for r in rows:
        (dup.append if r["article"] in seen else seen.add)(r["article"])
    data = {"source": {"ref": "SIE-LV10-2026",
                       "section": "Chapter 4 Residual Current Protective Devices, basic units: 5SV RCCBs type A, AC, F, B, B+ (1P+N, 3P+N)",
                       "note": "'version' standard = plain article (instantaneous); variants must be read on the cited page"},
            "rows": rows}
    OUT.write_text("# Generated by scripts/import_lv10_rccb.py — do not edit by hand.\n" +
                   yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200))
    from collections import Counter
    print(len(rows), "articles; duplicates:", dup, Counter((r["type"], r["poles"], r["version"][:8]) for r in rows))
