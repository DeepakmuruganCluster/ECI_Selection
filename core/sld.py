def _t(x, y, s, size=8, anchor="start", weight="normal", rot=None, cls="ink"):
    tr = f' transform="rotate({rot} {x} {y})"' if rot else ""
    return (f'<text x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}" font-weight="{weight}" class="{cls}"{tr}>'
            f"{escape(str(s))}</text>")


def _tag(x, y, tag):
    w = 7 + 6 * len(tag)
    return f'<rect x="{x}" y="{y - 9}" width="{w}" height="12" class="tag"/>' + _t(x + w / 2, y, tag, 8, "middle", "bold")


def _line(x1, y1, x2, y2, cls="wire"):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" class="{cls}"/>'


def _breaker(x, y, label="I>"):
    """Circuit-breaker / MPCB symbol: contact with a box carrying the trip mark."""
    return (_line(x, y - 18, x, y - 8) + _line(x, y - 8, x + 8, y + 6) + _line(x, y + 8, x, y + 18) +
            f'<rect x="{x - 22}" y="{y - 6}" width="14" height="12" class="sym"/>' + _t(x - 15, y + 3, label, 6, "middle"))


def _contact(x, y):
    """Contactor main contact (NO) with its coil mark."""
    return (_line(x, y - 18, x, y - 8) + _line(x, y - 8, x + 8, y + 6) + _line(x, y + 8, x, y + 18) +
            f'<circle cx="{x}" cy="{y - 8}" r="2" class="sym"/>')


def _fuse(x, y):
    return _line(x, y - 18, x, y - 9) + f'<rect x="{x - 4}" y="{y - 9}" width="8" height="18" class="sym"/>' + _line(x, y + 9, x, y + 18)


def _box(x, y, w, h, text, dashed=False):
    return (f'<rect x="{x - w / 2}" y="{y - h / 2}" width="{w}" height="{h}" class="{"nsel" if dashed else "sym"}"/>' +
            _t(x, y + 3, text, 7, "middle", "bold" if not dashed else "normal", cls="nsel-t" if dashed else "ink"))


def _motor(x, y, kw):
    return (f'<circle cx="{x}" cy="{y}" r="17" class="sym"/>' + _t(x, y - 1, "M", 9, "middle", "bold") +
            _t(x, y + 9, "3~", 7, "middle"))


def _lines_below(x, y, rows, size=6.5):
    return "".join(_t(x + 12, y + i * 9, r, size) for i, r in enumerate(rows) if r)


