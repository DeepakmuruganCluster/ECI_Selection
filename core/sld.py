            if kit.get(tag):
                lamps = sum(b["qty"] for b in kit[tag] if "lamp" in b["description"].lower() and isinstance(b["qty"], (int, float)))
                for b in kit[tag]:
                    mark(b["article"], tag, f"{tag} kit")
                g += [_t(x, 609, f"+ company kit: {lamps:g} lamp(s), terminals", 6, "middle"), _t(x, 617, "(see schedule)", 6, "middle")]
