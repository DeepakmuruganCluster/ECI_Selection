def _svg(g: list[str]) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">'
            f'<rect width="{W}" height="{H}" fill="#fff"/>{STYLE}{"".join(g)}</svg>')


def _control_sheet(v: dict, sheet: int, total: int, title: str, drg: str, level, mark) -> list[str]:
    """Control and automation: 230 V control circuit, 24 V DC and the PLC, measurement and protection at the incomer."""
    bom = v.get("bom") or []
    grp = lambda name: [b for b in bom if b["group"] == name]
    g = [_frame(sheet, total, title, drg, level), _t(40, 64, "CONTROL AND AUTOMATION", 13, weight="bold"),
         _t(40, 78, "from the main busbar; device data as selected, see the component schedule", 7)]

    # A. 230 V control supply and circuit
    x0, top = 120, 120
    cc = grp("Control circuit")
    tr = [b for b in cc if "transformer" in b["description"].lower()]
    mcb = [b for b in cc if "mcb" in b["description"].lower() or b["article"].upper().startswith(("5SL", "5SY", "MCB"))]
    g += [_t(x0, top - 18, "A · CONTROL SUPPLY 230 V AC", 9, weight="bold"), _line(x0, top, x0, top + 30)]
    supply = v.get("control_supply") or "transformer"
    scope = v.get("scope") or {}
    if scope.get("control_transformer") is False:      # R-REQ-31: not in this panel (a feeder kit fed from a main panel)
        g += [_box(x0, top + 48, 150, 30, "NO CONTROL TRANSFORMER IN THIS PANEL"), _t(x0 + 80, top + 58, "control supply from the main panel", 6.5)]
