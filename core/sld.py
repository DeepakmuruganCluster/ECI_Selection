def _schedule_rows(v: dict) -> list[dict]:
    """Every BOM line, actuator by actuator (in tag order), then the panel parts."""
    bom = [b for b in (v.get("bom") or []) if b["group"] != "Not selected"]
    tags = [f["tag"] for f in (v.get("feeders") or [])]
    first = lambda b: min([tags.index(t) for t in str(b.get("used_by") or "").split(", ") if t in tags] or [len(tags)])
    return sorted(bom, key=first)


def _schedule_sheet(rows, drawn, sheet, total, title, drg, level, n, of) -> list[str]:
    g = [_frame(sheet, total, title, drg, level),
         _t(40, 64, f"COMPONENT SCHEDULE{f' ({n}/{of})' if of > 1 else ''} — every selected part, actuator by actuator, then the panel", 11,
            weight="bold")]
    cols = [(40, "TAG"), (120, "USED BY"), (200, "GROUP"), (330, "ARTICLE"), (560, "DESCRIPTION"), (1010, "QTY")]
    y = 88
    g += [_t(x, y, h, 7, weight="bold") for x, h in cols] + [_line(36, y + 4, W - 36, y + 4, "thin")]
