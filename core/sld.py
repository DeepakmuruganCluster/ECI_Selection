"""Single line diagram (SLD) from a selection, in the layout of the company drawing set AVELCPSDL08WPLC.

A3 landscape sheets (SVG): frame with grid 1–6 / A–D, title block bottom right.
  Power sheets: incoming supply → incomer (1SQ1) → main busbar → one drop per feeder (protection → internal wiring
    → switching device → motor cable → motor, with the feeder's company-kit parts noted).
  Control and automation sheet: 230 V control supply (transformer or phase-neutral) → control MCBs → emergency stop,
    reset, lamps and coils; 24 V DC supply → PLC (CPU and modules) → interface relays → I/O terminals, PROFINET to the
    drives; incomer measurement and protection (CTs → energy meter, surge arrester, phase monitoring relay).
  Component schedule: every BOM line, actuator by actuator then the panel, with the tag it is drawn under — so every
    selected component is on the drawing.
Device tags follow the company legend (OWN-PROPEL-SCH160 p.3: 1SQ, Q, K, F, CT, H). Every part shown comes from the
selection; what is not selected is drawn dashed and says so. Standard library only.
"""
from __future__ import annotations

