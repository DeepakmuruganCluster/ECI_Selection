def _classify(articles: list[tuple[str, str, float]]) -> dict:
    """Split a feeder's BOM lines by device role (article prefixes of the makes used)."""
    out = {}
    for art, desc, qty in articles:
        a, d = art.upper(), desc.lower()
        role = ("ss" if a.startswith("3RW5") else "mpcb" if a.startswith(("3RV", "GZ1E", "GV", "3VA")) else "contactor" if a.startswith(("3RT", "LC1E")) else
                "fuse" if a.startswith("3NA") or "fuse" in d else "pm" if a.startswith("6SL3210") else
                "cu" if a.startswith(("6SL3243", "6SL3244", "6SL3246")) else "reactor" if a.startswith("6SL3203") else
                "olr" if a.startswith("LRE") or d.startswith("olr") or "overload" in d else
                "mpr" if "motor protection relay" in d else "timer" if "timer" in d else None)
        if role:
            out.setdefault(role, []).append((art, desc, qty))
    return out


