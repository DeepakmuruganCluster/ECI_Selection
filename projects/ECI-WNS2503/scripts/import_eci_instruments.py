"""Import the field devices (instruments, switches, valves, panel devices) of the ECI equipment specification.

    .venv/bin/python projects/ECI-WNS2503/scripts/import_eci_instruments.py

Source: ECI-WNS2503-EQUIP (Complete Equipment Panel Specification, 3 pages, one 19-column table).
Panel: rows before 'RO PANEL REQUIREMENTS' belong to BIO/UF, rows after it to RO. Motor rows (operating voltage
'… PH …') are kept as kind 'motor' for the I/O totals only; the load list (component 14) selects them. Values are copied as written.
"""
from __future__ import annotations

import re
from pathlib import Path

import pdfplumber
import yaml

ROOT = Path(__file__).resolve().parents[3]
PDF = ROOT / "sources" / "pdf" / "client" / "ECI-WNS2503" / "Complete Equipment Panel Specification_Siemens_Rev02_WNS2503_03062025.pdf"
COLS = ["sno", "item", "tag", "marking", "supply", "kw", "amps", "mpcb_rating", "mpcb", "qty", "total_kw", "inv", "dol", "ss",
        "di", "do", "ai_420", "ai_010", "ao"]


def num(v):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return 0


def kind(supply: str, item: str) -> str:
    """Device kind from the operating-voltage column (and the item name where the column is empty)."""
    s, it = supply.upper().replace(" ", ""), item.lower()
    if "230V" in s and "4-20" in s:
        return "mains_transmitter"          # analyser / flow meter: 230 V feed, active 4-20 mA output
    if "230VAC" in s:
        return "mains_valve"                # 230 V AC solenoid valve, switched by a PLC output
    if "0-10V" in s:
        return "pneumatic_panel"            # 24 V DC fed panel with 0-10 V signal
    if "4-20" in s:
        return "loop_transmitter"           # 2-wire loop-powered transmitter
    if "tower lamp" in it:
        return "tower_lamp"
    if "24V" in s:
        return "dc_switch"                  # 24 V DC dry contact / sensor to a PLC input (or a 24 V control signal)
    return "unstated"


def rows():
    out, panel, section = [], "BIO_UF", ""
    with pdfplumber.open(PDF) as pdf:
        for pno, page in enumerate(pdf.pages, 1):
            for t in page.extract_tables():
                for r in t:
                    r = [(c or "").replace("\n", " ").strip() for c in r] + [""] * 19
                    rec = dict(zip(COLS, r[:19]))
                    filled = [c for c in r if c]
                    if "RO PANEL REQUIREMENTS" in rec["sno"].upper():
                        panel = "RO"
                    if len(filled) <= 2 and filled and not filled[0].isdigit():
                        section = filled[0]
                        continue
                    if not rec["sno"].isdigit():
                        continue
                    supply, from_row = rec["supply"], False
                    if not supply:   # merged cells: the supply text sits in a neighbouring cell of the same row
                        m = re.search(r"230\s*V\s*,?\s*4-20\s*mA|230\s*V\s*AC|24\s*V\s*DC\s*/\s*0-10\s*V|24\s*V\s*D\s*C|24VDC|4-20\s*mA",
                                      " ".join(r[:9]), re.I)
                        supply, from_row = (m.group(0), True) if m else ("", False)
                    is_motor = "PH" in supply.upper()
                    k = "motor" if is_motor else kind(supply, rec["item"])
                    out.append({"panel": panel, "section": section, "item": rec["item"], "tag": rec["tag"],
                                "marking": rec["marking"], "supply": supply, "supply_from_row_text": from_row, "kind": k,
                                "qty": num(rec["qty"]),
                                "di": num(rec["di"]), "do": num(rec["do"]), "ai_420": num(rec["ai_420"]),
                                "ai_010": num(rec["ai_010"]), "ao": num(rec["ao"]), "page": pno})
    return out


if __name__ == "__main__":
    data = {"source": {"ref": "ECI-WNS2503-EQUIP",
                       "note": "field devices of the equipment specification table; 'page' = PDF page; motor rows are in the load list"},
            "rows": rows()}
    p = ROOT / "projects" / "ECI-WNS2503" / "data" / "eci_wns2503_field_devices.yaml"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("# Generated by projects/ECI-WNS2503/scripts/import_eci_instruments.py — do not edit by hand.\n" +
                 yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200))
    from collections import Counter
    print(len(data["rows"]), "rows;", Counter((r["panel"], r["kind"]) for r in data["rows"]))
