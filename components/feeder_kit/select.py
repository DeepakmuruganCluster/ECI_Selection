"""Feeder kit: the company (Propel) standard BOM structure for a motor feeder, checked against the motor.

Rules: rules.yaml (R-KIT-01 … 05). Data: data/propel_dol_kits.yaml (OWN-PROPEL-DOL), data/propel_panel_kits.yaml
(OWN-PROPEL-COST), both generated by scripts/import_propel.py.
"""
from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

from components.motor_flc.select import select as motor_flc
from core.provenance import load_sourced_table, load_yaml
from core.result import INFO, PASS, WARN, Result
from core.data import data_file

HERE = Path(__file__).parent
COMPONENT = "feeder_kit"
STARTERS = ("DOL", "DOL_FR", "SD", "VFD")


@lru_cache(maxsize=None)
def _rules() -> dict:
    return load_yaml(HERE / "rules.yaml")


@lru_cache(maxsize=None)
def _kits() -> list[dict]:
    out = []
    for f in ("propel_dol_kits.yaml", "propel_panel_kits.yaml"):
        d = load_sourced_table(data_file(f), ("title", "sheet", "items"))
        out += [{**k, "ref": d["source"]["ref"]} for k in d["rows"]]
    return out


def _amps(rating: str) -> list[float]:
    return [float(x) for x in re.findall(r"(\d+(?:\.\d+)?)\s*-?\s*", rating or "") if x]


def _rated_a(item: dict):
    m = re.search(r"(\d+(?:\.\d+)?)\s*A", item.get("rating") or "")
    return float(m.group(1)) if m else None


def _src(kit: dict, row=None) -> str:
    return f"{kit['ref']} sheet '{kit['sheet'].strip()}' row {row or kit['row']}"


def kit_id(k: dict) -> str:
    """A short, space-free id of a kit (it travels in a load-list line as kit=…)."""
    import hashlib
    return "KIT-" + hashlib.sha1(f"{k['ref']}|{k['sheet'].strip()}|{k.get('row') or 0}|{k['title']}".encode()).hexdigest()[:8]


def select(starter: str, kw: float, motors: int = 1, application: str | None = None, flc_a: float | None = None,
           voltage_v: float = 400.0, kit: str | None = None) -> Result:
    inputs = {k: v for k, v in locals().items() if v is not None}
    res = Result(COMPONENT, inputs)
    starter = (starter or "").upper()
    if starter not in STARTERS:
        return res.invalid(f"starter must be one of {', '.join(STARTERS)} (got {starter})")
    if kw <= 0 or motors < 1:
        return res.invalid("kW must be > 0 and motors ≥ 1")

    # R-KIT-01: the company kit
    fit = [k for k in _kits() if k["starter"] == starter and float(kw) in k["kw_options"] and k["motors"] == motors]
    if application:
        words = [w for w in re.split(r"\W+", application.lower()) if w]
        narrowed = [k for k in fit if all(w in k["title"].lower().replace(" ", "") or w in k["title"].lower() for w in words)]
        fit = narrowed
    if not fit:
        what = "VFD BOM structure not received yet" if starter == "VFD" else "no company kit for this starter, power and motors"
        return res.refuse("R-KIT-01", f"company kit for {starter} {kw:g} kW × {motors}" +
                          (f" ({application})" if application else ""), what)
    if kit is not None:                          # the designer's choice among the kits that fit
        chosen = [k for k in fit if kit_id(k) == kit]
        if not chosen:
            return res.refuse("R-KIT-06", "the chosen company kit fits this starter, power and motors",
                              f"{kit} is not one of: {'; '.join(k['title'] for k in fit)}")
        fit = chosen
    if len(fit) > 1:                             # audit 2026-10-17 (owner: ask): never the first of several silently
        res.refuse("R-KIT-06", "one company kit for this starter, power and application",
                   f"{len(fit)} kits fit: " + "; ".join(k["title"] for k in fit) + " — choose one")
        res.value = {"choices": [{"id": kit_id(k), "title": k["title"], "sheet": k["sheet"].strip()} for k in fit]}
        return res
    kit = fit[0]
    res.add("R-KIT-01", "company standard kit", kit["title"], PASS, _src(kit))

    # motor current: nameplate, else the guide table (component 1)
    if flc_a is None:
        f = motor_flc(kw=kw, load_type="motor", voltage_v=voltage_v, phases=3)
        flc = f.value.get("flc_a") if f.value else None
        basis = "guide table (component 1)" if flc else "not in the guide table: give the nameplate current"
    else:
        flc, basis = float(flc_a), "nameplate"
    items = kit["items"]
    first = lambda role: next((i for i in items if i["role"] == role), None)
    value = {"kit": kit["title"], "kit_id": kit_id(kit), "sheet": kit["sheet"].strip(), "kit_source": _src(kit), "flc_a": flc, "n_items": len(items)}

    if starter in ("DOL", "DOL_FR"):
        mp, ct = first("mpcb"), first("contactor")
        value.update({"mpcb": mp and mp["article"], "contactor": ct and ct["article"]})
        rng = _amps(mp["rating"]) if mp else []
        if flc is None:
            res.add("R-KIT-03", "motor current inside the kit's MPCB range", f"motor current {basis}: not checked", WARN)
        elif len(rng) >= 2:
            ok = rng[0] <= flc <= rng[1]
            res.add("R-KIT-03", f"motor current {flc:g} A ({basis}) inside MPCB range",
                    f"{mp['article']} {rng[0]:g} … {rng[1]:g} A", PASS if ok else WARN, _src(kit, mp["row"]))
        if flc is not None and ct and _rated_a(ct) is not None:
            ok = _rated_a(ct) >= flc
            res.add("R-KIT-04", f"contactor rating ≥ motor current {flc:g} A", f"{ct['article']} {_rated_a(ct):g} A",
                    PASS if ok else WARN, _src(kit, ct["row"]))
    elif starter == "SD":
        cts = sorted((i for i in items if i["role"] == "contactor" and _rated_a(i)), key=lambda i: -_rated_a(i))
        pair = next((i for i in cts if (i["qty"] or 0) >= 2), None)
        star = next((i for i in cts if i is not pair), None)
        value.update({"line_contactor": pair and pair["article"], "star_contactor": star and star["article"]})
        r3 = _rules()["params"]["sqrt3"]
        if flc is None:
            res.add("R-KIT-05", "star-delta contactors against the motor current", f"motor current {basis}: not checked", WARN)
        else:
            if pair:
                res.add("R-KIT-05", f"line and delta contactors ≥ FLC/√3 = {flc / r3:.1f} A",
                        f"{pair['article']} × {pair['qty']:g}, {_rated_a(pair):g} A", PASS if _rated_a(pair) >= flc / r3 else WARN,
                        _src(kit, pair["row"]))
            if star:
                res.add("R-KIT-05", f"star contactor ≥ FLC/3 = {flc / 3:.1f} A", f"{star['article']}, {_rated_a(star):g} A",
                        PASS if _rated_a(star) >= flc / 3 else WARN, _src(kit, star["row"]))
            olrs = [i for i in items if i["role"] == "overload_relay"]
            if len(olrs) == 1:
                rng = _amps(olrs[0]["rating"])
                ok = len(rng) >= 2 and rng[0] <= flc / r3 <= rng[1]
                res.add("R-KIT-05", f"overload relay range contains FLC/√3 = {flc / r3:.1f} A",
                        f"{olrs[0]['article']} {olrs[0]['rating']}", PASS if ok else WARN, _src(kit, olrs[0]["row"]))
            elif olrs:
                res.add("R-KIT-05", "overload relay", f"{len(olrs)} relays (auxiliary motors too): not checked", INFO)

    # R-KIT-02: indicative price
    priced = [i for i in items if i["unit_price_inr"] is not None]
    unpriced = [i["description"] for i in items if i["unit_price_inr"] is None]
    total = round(sum(i["unit_price_inr"] * (i["qty"] or 0) for i in priced), 2)
    res.add("R-KIT-02", "indicative kit price (INR, company sheet)",
            f"₹{total:,.2f}" + (f"; not priced: {', '.join(unpriced)}" if unpriced else ""), INFO, _src(kit))
    value.update({"price_inr": total, "price_complete": not unpriced,
                  "items": [{"role": i["role"], "description": i["description"], "rating": i["rating"], "make": i["make"],
                             "article": i["article"], "qty": i["qty"], "unit_price_inr": i["unit_price_inr"],
                             "source": _src(kit, i["row"])} for i in items]})
    res.value, res.basis = value, "company standard kit"
    return res


from core.guard import guarded  # noqa: E402  (fail closed on bad input: NaN, inf, negative, text)

select = guarded(select)
